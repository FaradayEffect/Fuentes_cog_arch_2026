"""Small changes to the Nav2 parameter file so that it fits our world.

Pure Python (no ROS import), so it can be tested on any computer.
The starting point is the file of TurtleBot3 (turtlebot3_navigation2/param/burger.yaml).
We do not copy the whole file into the repository: we read the installed one and patch it.
"""
from __future__ import annotations

import math
from typing import Any, Dict, List, Tuple

# TurtleBot3 Burger is round with a radius of about 0.105 m.
ROBOT_RADIUS = 0.12
INFLATION_RADIUS = 0.40
# With the forklift the robot is longer (see arm_model.REACH), and the cube it carries is right in front of
# the lidar (13-17 cm; the forks and the pallet are lower than the lidar). Lidar points closer than
# SELF_FILTER are its own load: AMCL and the costmaps skip them.
FORKLIFT_INFLATION = 0.55
SELF_FILTER = 0.25


def _set_everywhere(obj: Any, key: str, value: Any, path: str = "") -> List[str]:
    """Set `key` to `value` in every dict (at any depth) that already has this key."""
    changed: List[str] = []
    if isinstance(obj, dict):
        for k, v in obj.items():
            here = f"{path}/{k}" if path else str(k)
            if k == key:
                obj[k] = value
                changed.append(here)
            else:
                changed += _set_everywhere(v, key, value, here)
    elif isinstance(obj, list):
        for i, v in enumerate(obj):
            changed += _set_everywhere(v, key, value, f"{path}[{i}]")
    return changed


def _laser_sources(obj: Any) -> List[Dict[str, Any]]:
    """Every observation source of the costmaps that reads the lidar (a dict with data_type: LaserScan)."""
    found: List[Dict[str, Any]] = []
    if isinstance(obj, dict):
        if str(obj.get("data_type", "")).strip('"') == "LaserScan":
            found.append(obj)
        for v in obj.values():
            found += _laser_sources(v)
    elif isinstance(obj, list):
        for v in obj:
            found += _laser_sources(v)
    return found


def _xy_yaw(start) -> Tuple[float, float, float]:
    """The start pose can be a Pose2D (has x, y, yaw) or a tuple (x, y, yaw)."""
    if hasattr(start, "x") and hasattr(start, "y") and hasattr(start, "yaw"):
        return float(start.x), float(start.y), float(start.yaw)
    x, y, yaw = (float(v) for v in start)
    return x, y, yaw


def patch_params(data: Dict[str, Any], robot_start, robot_radius: float = ROBOT_RADIUS,
                 inflation_radius: float = INFLATION_RADIUS, use_sim_time: bool = True,
                 self_filter: float = 0.0) -> List[str]:
    """Edit the loaded yaml (a dict) in place. Returns short messages about what changed."""
    notes: List[str] = []
    x, y, yaw = _xy_yaw(robot_start)

    amcl = data.get("amcl", {}).get("ros__parameters") if isinstance(data.get("amcl"), dict) else None
    if isinstance(amcl, dict):
        amcl["set_initial_pose"] = True
        amcl["initial_pose"] = {"x": x, "y": y, "z": 0.0, "yaw": yaw}
        notes.append(f"amcl: initial pose = ({x:.2f}, {y:.2f}, {math.degrees(yaw):.0f} deg)")
    else:
        notes.append("amcl section not found: the agent publishes /initialpose by itself")

    for key, value in (("robot_radius", robot_radius), ("inflation_radius", inflation_radius)):
        where = _set_everywhere(data, key, value)
        notes.append(f"{key} = {value} in {len(where)} place(s)")

    if self_filter > 0:
        # also in the sources that do not have the key yet (Nav2 Humble knows it, the default is 0)
        if isinstance(amcl, dict):
            amcl["laser_min_range"] = self_filter
        sources = _laser_sources(data)
        for source in sources:
            source["obstacle_min_range"] = self_filter
        notes.append(f"lidar points closer than {self_filter} m are skipped (the robot's own forks and load): "
                     f"amcl laser_min_range, obstacle_min_range in {len(sources)} lidar source(s)")

    if use_sim_time:
        where = _set_everywhere(data, "use_sim_time", True)
        notes.append(f"use_sim_time = true in {len(where)} place(s)")
    return notes


def write_patched(source_path: str, target_path: str, robot_start, **kw) -> List[str]:
    import os
    import yaml   # PyYAML is part of every ROS 2 installation

    with open(source_path, encoding="utf-8") as f:
        data = yaml.safe_load(f)
    notes = patch_params(data, robot_start, **kw)
    os.makedirs(os.path.dirname(os.path.abspath(target_path)), exist_ok=True)
    with open(target_path, "w", encoding="utf-8") as f:
        f.write("# Generated by actr_lab1 from " + source_path + "\n")
        yaml.safe_dump(data, f, default_flow_style=False, sort_keys=False)
    return notes
