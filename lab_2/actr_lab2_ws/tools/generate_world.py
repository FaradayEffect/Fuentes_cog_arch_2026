def write_world(root=PKG):
    path = paths(root)["world"]
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(build_world())


# ----------------------------------------------------------------------- places
def cube_aliases(name):
    n = name.split("_")[-1]
    return [name, f"cube {n}", f"cube{n}", f"кубик {n}", f"куб {n}", f"кубика {n}", f"кубику {n}"]


def build_places():
    places = {}
    for name, room in list(L.ROOMS.items()) + list(L.RESTRICTED.items()):
        places[name] = {
            "kind": room["kind"],
            "polygon": room["polygon"],
            "waypoints": [[round(v, 4) for v in wp] for wp in room["waypoints"]],
            "aliases": room["aliases"],
        }
    cubes = {n: {"start": i["start"], "aliases": cube_aliases(n)} for n, i in L.CUBES.items()}
    return {
        "frame": "map",
        "robot_start": [round(v, 4) for v in L.ROBOT_START],
        "robot_radius": L.ROBOT_RADIUS,
        "cube_size": L.CUBE_SIZE,
        "pallet_height": round(L.PALLET_H, 4),
        "pallet_size": L.PALLET_SIZE,
        "goal_room": L.GOAL_ROOM,
        "forbidden": list(L.RESTRICTED.keys()),
        "places": places,
        "cubes": cubes,
        "map_yaml": "maps/rooms.yaml",
    }


def write_places(root=PKG):
    path = paths(root)["places"]
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(build_places(), f, indent=2, ensure_ascii=False)
        f.write("\n")


def generate(root=PKG):
    """Write all generated files below `root` and return their paths."""
    w, h = write_map(root)
    write_world(root)
    write_places(root)
    return paths(root), (w, h)


def main():
    pth, (w, h) = generate()
    print(f"map    : {pth['pgm']} ({w}x{h} px, {L.RESOLUTION} m/px)")
    print(f"map    : {pth['yaml']}")
    print(f"world  : {pth['world']}")
    print(f"places : {pth['places']}")


if __name__ == "__main__":
    main()
