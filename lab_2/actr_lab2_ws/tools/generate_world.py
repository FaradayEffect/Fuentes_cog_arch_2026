"""Generate the Gazebo world, the Nav2 map and places.json from world_layout.py.

Run from the workspace root:

    python3 tools/generate_world.py

The files are written into src/actr_lab1/{worlds,maps,config}.
"""
import json
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

import world_layout as L  # noqa: E402

PKG = os.path.join(ROOT, "src", "actr_lab1")


def paths(root=PKG):
    return {
        "world": os.path.join(root, "worlds", "rooms.world"),
        "pgm": os.path.join(root, "maps", "rooms.pgm"),
        "yaml": os.path.join(root, "maps", "rooms.yaml"),
        "places": os.path.join(root, "config", "places.json"),
    }


# --------------------------------------------------------------------------- map
def map_size():
    width = int(round((L.MAP_X1 - L.MAP_X0) / L.RESOLUTION))
    height = int(round((L.MAP_Y1 - L.MAP_Y0) / L.RESOLUTION))
    return width, height


def inside_box(x, y, b):
    return abs(x - b.cx) <= b.sx / 2 and abs(y - b.cy) <= b.sy / 2


def rasterize():
    """Return the map as bytes. Row 0 of the image is the top (largest y)."""
    width, height = map_size()
    boxes = list(L.WALLS) + list(L.OBSTACLES)
    data = bytearray(width * height)
    for row in range(height):
        y = L.MAP_Y1 - (row + 0.5) * L.RESOLUTION
        for col in range(width):
            x = L.MAP_X0 + (col + 0.5) * L.RESOLUTION
            if any(inside_box(x, y, b) for b in boxes):
                value = 0            # occupied
            elif L.X_MIN < x < L.X_MAX and L.Y_MIN < y < L.Y_MAX:
                value = 254          # free
            else:
                value = 205          # unknown (outside the building)
            data[row * width + col] = value
    return width, height, bytes(data)


def write_map(root=PKG):
    pth = paths(root)
    width, height, data = rasterize()
    os.makedirs(os.path.dirname(pth["pgm"]), exist_ok=True)
    with open(pth["pgm"], "wb") as f:
        f.write(f"P5\n# generated by tools/generate_world.py\n{width} {height}\n255\n".encode("ascii"))
        f.write(data)
    with open(pth["yaml"], "w") as f:
        f.write("image: rooms.pgm\n")
        f.write("mode: trinary\n")
        f.write(f"resolution: {L.RESOLUTION}\n")
        f.write(f"origin: [{L.MAP_X0:.2f}, {L.MAP_Y0:.2f}, 0.0]\n")
        f.write("negate: 0\n")
        f.write("occupied_thresh: 0.65\n")
        f.write("free_thresh: 0.196\n")
    return width, height


# -------------------------------------------------------------------------- world
def color(c):
    return " ".join(f"{v:g}" for v in c)


def box_xml(b, indent="        "):
    z = b.height / 2
    pose = f"{b.cx:g} {b.cy:g} {z:g} 0 0 0"
    size = f"{b.sx:g} {b.sy:g} {b.height:g}"
    col = color(b.color)
    return (
        f"{indent}<collision name=\"{b.name}_col\">\n"
        f"{indent}  <pose>{pose}</pose>\n"
        f"{indent}  <geometry><box><size>{size}</size></box></geometry>\n"
        f"{indent}</collision>\n"
        f"{indent}<visual name=\"{b.name}_vis\">\n"
        f"{indent}  <pose>{pose}</pose>\n"
        f"{indent}  <geometry><box><size>{size}</size></box></geometry>\n"
        f"{indent}  <material><ambient>{col}</ambient><diffuse>{col}</diffuse></material>\n"
        f"{indent}</visual>\n"
    )


def floor_xml(name, polygon, rgba):
    xs = [p[0] for p in polygon]
    ys = [p[1] for p in polygon]
    cx, cy = (min(xs) + max(xs)) / 2, (min(ys) + max(ys)) / 2
    sx, sy = max(xs) - min(xs), max(ys) - min(ys)
    col = color(rgba)
    return (
        f"        <visual name=\"{name}_floor\">\n"
        f"          <pose>{cx:g} {cy:g} 0.003 0 0 0</pose>\n"
        f"          <geometry><box><size>{sx:g} {sy:g} 0.006</size></box></geometry>\n"
        f"          <material><ambient>{col}</ambient><diffuse>{col}</diffuse></material>\n"
        f"        </visual>\n"
    )


WOOD = "0.72 0.55 0.33 1"


def pallet_parts():
    """(name, centre, size) of the pallet boxes. Heights are relative to the CENTRE OF THE CUBE (the origin
    of the model), so the bottom of the pallet is at -(PALLET_H + CUBE_SIZE / 2)."""
    s = L.CUBE_SIZE
    bottom = -(L.PALLET_H + s / 2)
    parts = []
    for i, bx in enumerate(L.PALLET_BLOCKS):
        for j, by in enumerate(L.PALLET_BLOCKS):
            parts.append((f"block_{i}{j}", (bx, by, bottom + L.PALLET_BLOCK_H / 2),
                          (L.PALLET_BLOCK, L.PALLET_BLOCK, L.PALLET_BLOCK_H)))
    parts.append(("deck", (0.0, 0.0, bottom + L.PALLET_BLOCK_H + L.PALLET_DECK_H / 2),
                  (L.PALLET_SIZE, L.PALLET_SIZE, L.PALLET_DECK_H)))
    return parts


def _part_xml(kind, name, centre, size, col=""):
    cx, cy, cz = centre
    sx, sy, sz = size
    xml = (f"        <{kind} name=\"{name}\">\n"
           f"          <pose>{cx:g} {cy:g} {cz:.4f} 0 0 0</pose>\n"
           f"          <geometry><box><size>{sx:g} {sy:g} {sz:g}</size></box></geometry>\n")
    if kind == "visual":
        xml += f"          <material><ambient>{col}</ambient><diffuse>{col}</diffuse></material>\n"
    else:
        xml += "          <surface><friction><ode><mu>1.0</mu><mu2>1.0</mu2></ode></friction></surface>\n"
    return xml + f"        </{kind}>\n"


def cube_xml(name, info):
    """A cube standing on a small pallet: ONE rigid body (the cube is strapped to its pallet).
    The origin of the model is the centre of the cube."""
    s = L.CUBE_SIZE
    x, y = info["start"]
    col = color(info["color"])
    m = L.CUBE_MASS
    h = L.PALLET_H + s                      # whole height
    ixx = m * (L.PALLET_SIZE ** 2 + h * h) / 12.0
    izz = m * (2 * L.PALLET_SIZE ** 2) / 12.0
    collisions = pallet_parts()
    parts = "".join(_part_xml("collision", f"{n}_collision", c, sz) for n, c, sz in collisions)
    # visuals: the same blocks, and 5 boards on top instead of one plate (it looks like a pallet)
    parts += "".join(_part_xml("visual", f"{n}_visual", c, sz, WOOD) for n, c, sz in collisions if n != "deck")
    _n, (dx, dy, dz), (px, py, pz) = collisions[-1]
    for i in range(5):
        bx = -px / 2 + 0.024 + i * (px - 0.048) / 4
        parts += _part_xml("visual", f"board_{i}_visual", (bx, 0.0, dz), (0.04, py, pz), WOOD)
    return f"""    <model name="{name}">
      <pose>{x:g} {y:g} {L.PALLET_H + s / 2 + 0.001:.4f} 0 0 0</pose>
      <link name="link">
        <inertial>
          <pose>0 0 -0.03 0 0 0</pose>
          <mass>{m:g}</mass>
          <inertia>
            <ixx>{ixx:.7f}</ixx><iyy>{ixx:.7f}</iyy><izz>{izz:.7f}</izz>
            <ixy>0</ixy><ixz>0</ixz><iyz>0</iyz>
          </inertia>
        </inertial>
        <collision name="cube_collision">
          <geometry><box><size>{s:g} {s:g} {s:g}</size></box></geometry>
          <surface><friction><ode><mu>1.0</mu><mu2>1.0</mu2></ode></friction></surface>
        </collision>
        <visual name="cube_visual">
          <geometry><box><size>{s:g} {s:g} {s:g}</size></box></geometry>
          <material><ambient>{col}</ambient><diffuse>{col}</diffuse></material>
        </visual>
{parts}      </link>
    </model>
"""


